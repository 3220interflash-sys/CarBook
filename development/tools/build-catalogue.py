# Builds the parts catalogue (catalogue.js and its wording in strings.js) from the owner's
# "Vehicle maintenance master checklist" research, saved as research/maintenance-checklist/items.json.
# Run from the main folder: python3 development/tools/build-catalogue.py
# It rewrites catalogue.js and the generated block in strings.js between the CATALOGUE markers.
import json, re

SRC = 'research/maintenance-checklist/items.json'
rows = json.load(open(SRC))

GROUPS = {  # section number -> (group key, icon, group name)
    1: ('engine', 'tuneup', 'Engine'), 2: ('fluids', 'drop', 'Fluids and oils'), 3: ('filters', 'filter', 'Filters'),
    4: ('brakes', 'brake', 'Brakes'), 5: ('tyres', 'tyre', 'Tyres, wheels and suspension'), 6: ('electrical', 'battery', 'Battery and electrical'),
    7: ('cooling', 'therm', 'Cooling'), 8: ('fuel', 'fuel', 'Fuel system'), 9: ('drivetrain', 'gear', 'Gearbox, clutch and drivetrain'),
    10: ('ac', 'fan', 'Air conditioning'), 11: ('body', 'car', 'Body and interior'), 12: ('diagnostics', 'gauge', 'Tune-ups and diagnostics'),
    13: ('hybrid', 'battery', 'Hybrid'), 14: ('ev', 'battery', 'Electric vehicle'), 15: ('moto', 'wrench', 'Motorbike and scooter'),
}
# Parts the app already tracks in Car health: picking these opens the existing part instead of adding a copy.
CORE = {'engine oil': 'Oil change', 'air filter': 'Air filter', 'engine air filter': 'Air filter', 'spark plugs (standard)': 'Spark plugs',
        'engine tune-up / diagnostics': 'Engine tune-up', 'brake pads (front)': 'Brake pads', 'brake fluid': 'Brake fluid',
        'coolant / antifreeze': 'Coolant', 'coolant': 'Coolant', 'cabin / ac filter': 'AC filter', 'cabin air filter': 'AC filter',
        'manual transmission oil': 'Gearbox oil', 'manual gearbox oil': 'Gearbox oil', 'tyres (age)': 'Tyres', 'wheel alignment': 'Wheel alignment',
        'main battery': 'Battery', 'wiper blades': 'Wiper blades'}

def interval(text):
    """Suggested reminder from a typical range: the shorter end, by km and/or months. None when condition-based."""
    t = text.replace('–', '-').replace('—', '-').lower()
    km = re.search(r'([\d,]{3,})(?:\s*-\s*[\d,]+)?\+?\s*km', t)
    mo = re.search(r'(\d+)(?:\s*-\s*\d+)?\s*months?', t)
    yr = re.search(r'(\d+)(?:\s*-\s*\d+)?\s*years?', t)
    months = int(mo.group(1)) if mo else int(yr.group(1)) * 12 if yr else None
    if months is None and re.search(r'\bannual|every 12 months|yearly', t): months = 12
    return (int(km.group(1).replace(',', '')) if km else None), months

def slug(s): return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')[:40]

items, seen, words = [], set(), {}
for r in rows:
    sec = int(r['section'].split('.')[0])
    if sec not in GROUPS: continue
    cells = r['row']; name = cells[0].strip()
    if not name or name.lower() in seen: continue
    seen.add(name.lower())
    check = cells[1].strip() if len(cells) > 1 else ''
    typical = cells[2].strip() if len(cells) > 2 else ''
    km, months = interval(typical or check)
    g = GROUPS[sec]
    cid = slug(g[0] + '-' + name)
    it = {'id': cid, 'g': g[0]}
    if km: it['km'] = km
    if months: it['months'] = months
    low = name.lower()
    if sec == 13: it['fuels'] = ['Hybrid']
    elif sec == 14: it['fuels'] = ['Electric']
    elif sec == 15 or 'motorcycle' in low: it['types'] = ['Motorbike']
    if 'diesel' in low: it['fuels'] = ['Diesel']
    if 'petrol' in low: it['fuels'] = ['Petrol', 'Hybrid']
    if 'ev ' in low or low.startswith('ev'): it['fuels'] = ['Electric']
    if '4wd' in low: it['types'] = ['Car', 'Van']
    if low in CORE: it['core'] = CORE[low]
    items.append(it)
    words[f'cat_{cid}_name'] = name
    words[f'cat_{cid}_check'] = check
    words[f'cat_{cid}_typical'] = typical

js = ('// Parts catalogue: about 250 parts from the owner\'s maintenance checklist research\n'
      '// (research/maintenance-checklist/). Built by development/tools/build-catalogue.py; edit the research, then rebuild.\n'
      '// Each part: id, g (group), km and months (suggested reminder: the shorter end of the typical range; none when\n'
      '// condition-based), fuels or types it applies to, and core (a part Car health already tracks).\n'
      '// Wording lives in strings.js as cat_<id>_name, _check and _typical. These are defaults; the owner\'s manual comes first.\n'
      'const CATALOGUE_GROUPS = ' + json.dumps({g[0]: g[1] for g in GROUPS.values()}) + ';\n'
      'const CATALOGUE = [\n' + ',\n'.join('  ' + json.dumps(i, ensure_ascii=False) for i in items) + '\n];\n')
open('catalogue.js', 'w').write(js)

s = open('strings.js').read()
block = '    // CATALOGUE START (generated by development/tools/build-catalogue.py)\n'
block += ''.join(f'    catg_{g[0]}: {json.dumps(g[2])},\n' for g in GROUPS.values())
block += ''.join(f'    {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)},\n' for k, v in words.items())
block += '    // CATALOGUE END\n'
if '// CATALOGUE START' in s:
    s = re.sub(r'    // CATALOGUE START.*?    // CATALOGUE END\n', lambda m: block, s, flags=re.S)
else:
    anchor = "    'svc_Other': 'Other',\n"
    assert s.count(anchor) == 1
    s = s.replace(anchor, anchor + block)
open('strings.js', 'w').write(s)
withiv = sum(1 for i in items if 'km' in i or 'months' in i)
print(len(items), 'parts;', withiv, 'with a suggested interval;', sum(1 for i in items if 'core' in i), 'linked to existing parts')
